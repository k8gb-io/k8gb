import (
	"fmt"
	"strings"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// ZoneDelegationSpec defines the desired state of ZoneDelegation
// +kubebuilder:validation:XValidation:rule="self.loadBalancedZone != self.parentZone",message="loadBalancedZone must not equal parentZone"
// +kubebuilder:validation:XValidation:rule="self.loadBalancedZone.endsWith('.' + self.parentZone)",message="loadBalancedZone must be subdomain"
type ZoneDelegationSpec struct {
	// LoadBalancedZone is the DNS zone managed by this ZoneDelegation
	LoadBalancedZone string `json:"loadBalancedZone"`

	// ParentZone is the zone under which this load-balanced zone is delegated
	ParentZone string `json:"parentZone"`

	// DNSZoneNegTTL specifies the negative TTL for the DNS zone (in seconds)
	DNSZoneNegTTL int `json:"dnsZoneNegTTL"`

	// DoFinalize indicates that this ZoneDelegation should be withdrawn
	// from edge DNS. The controller removes the delegation only when it is no
	// longer served by any known cluster (based on configured geoTags).
	// +kubebuilder:default=false
	DoFinalize bool `json:"doFinalize,omitempty"`
}

// ZoneDelegationStatus defines the observed state of ZoneDelegation
type ZoneDelegationStatus struct {
	// DNSServers lists the authoritative DNS servers for the delegated zone
	DNSServers []DNSServer `json:"dnsServers,omitempty"`
}

// DNSServer represents a single DNS server for a zone delegation
type DNSServer struct {
	// Name of the DNS server (FQDN)
	Name string `json:"name"`

	// Address of the DNS server (IPv4 or IPv6)
	Address string `json:"address"`
}

// ZoneDelegation is the Schema for the zonedelegations API
// +kubebuilder:object:root=true
// +kubebuilder:subresource:status
// +kubebuilder:resource:scope=Cluster,shortName=zd
// +kubebuilder:printcolumn:name="LoadBalancedZone",type=string,JSONPath=`.spec.loadBalancedZone`
// +kubebuilder:printcolumn:name="ParentZone",type=string,JSONPath=`.spec.parentZone`
// +kubebuilder:printcolumn:name="NegTTL",type=integer,JSONPath=`.spec.dnsZoneNegTTL`
type ZoneDelegation struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   ZoneDelegationSpec   `json:"spec,omitempty"`
	Status ZoneDelegationStatus `json:"status,omitempty"`
}

// +kubebuilder:object:root=true

// ZoneDelegationList contains a list of ZoneDelegation
type ZoneDelegationList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`
	Items           []ZoneDelegation `json:"items"`
}

func (l *ZoneDelegationList) ContainsZone(host string) bool {
	for _, z := range l.Items {
		if strings.Contains(host, z.Spec.LoadBalancedZone) {
			return true
		}
	}
	return false
}

func (l *ZoneDelegationList) FindZone(host string) (bool, ZoneDelegation) {
	for _, z := range l.Items {
		if strings.Contains(host, z.Spec.LoadBalancedZone) {
			return true, z
		}
	}
	return false, ZoneDelegation{}
}

func (l *ZoneDelegationList) ListZones() []string {
	var zones []string
	for _, z := range l.Items {
		zones = append(zones, z.Spec.LoadBalancedZone)
	}
	return zones
}

func (z *ZoneDelegation) IsInDeletion() bool {
	return z.DeletionTimestamp != nil
}

func (z *ZoneDelegation) nsSuffix() string {
	d := strings.TrimSuffix(z.Spec.LoadBalancedZone, "."+z.Spec.ParentZone)
	domainX := strings.ReplaceAll(d, ".", "-")
	return fmt.Sprintf("-%s.%s", domainX, z.Spec.ParentZone)
}

func (z *ZoneDelegation) ExtractGeoTagFromGlueA(glueA string, prefix string) string {
	const defaultPrefix = "gslb-ns-"
	glueA = strings.TrimSuffix(glueA, ".")
	res := strings.TrimPrefix(glueA, prefix)
	// if local cluster prefix is "custom"
	// we still need to find external cluster tag which still
	// pre-custom tag. Note a new Custom tag should be used across cluster memebers
	if prefix != defaultPrefix {
		res = strings.TrimPrefix(res, defaultPrefix)
	}
	suffix := z.nsSuffix()
	return strings.ReplaceAll(res, suffix, "")
}

// GetExternalDNSEndpointName returns name of endpoint sitting in k8gb namespace
func (z *ZoneDelegation) GetExternalDNSEndpointName() string {
	var suffix = strings.Trim(strings.ReplaceAll(z.Spec.LoadBalancedZone, ".", "-"), " ")
	return fmt.Sprintf("k8gb-ns-extdns-%s", suffix)
}

// GetExternalDNSNsMergeEndpointName is the shared-owner NS DNSEndpoint used
// when ExtDNSNsMergeEnabled is set. Glue A stays on GetExternalDNSEndpointName.
func (z *ZoneDelegation) GetExternalDNSNsMergeEndpointName() string {
	var suffix = strings.Trim(strings.ReplaceAll(z.Spec.LoadBalancedZone, ".", "-"), " ")
	return fmt.Sprintf("k8gb-ns-extdns-ns-%s", suffix)
}
