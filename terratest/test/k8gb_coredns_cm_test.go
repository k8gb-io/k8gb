import (
	"os"
	"path/filepath"
	"testing"

	"github.com/gruntwork-io/terratest/modules/helm"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestCoreDNSConfigMapExtraServerBlocks(t *testing.T) {
	t.Parallel()

	helmChartPath, err := filepath.Abs("../../chart/k8gb")
	require.NoError(t, err)

	t.Run("renders extraServerBlocks in Corefile when configured", func(t *testing.T) {
		tmpDir := t.TempDir()
		valuesPath := filepath.Join(tmpDir, "values.yaml")
		valuesContent := "extraServerBlocks: |\n  example.com:5353 {\n    errors\n    forward . /etc/resolv.conf\n  }\n"
		err := os.WriteFile(valuesPath, []byte(valuesContent), 0600)
		require.NoError(t, err)

		options := &helm.Options{
			ValuesFiles: []string{valuesPath},
		}

		output := helm.RenderTemplate(t, options, helmChartPath, "k8gb-test", []string{"templates/coredns/cm.yaml"})

		assert.Contains(t, output, "example.com:5353 {")
		assert.Contains(t, output, "forward . /etc/resolv.conf")
	})

	t.Run("renders template evaluation inside extraServerBlocks", func(t *testing.T) {
		tmpDir := t.TempDir()
		valuesPath := filepath.Join(tmpDir, "values.yaml")
		valuesContent := "extraServerBlocks: |\n  {{ .Values.k8gb.clusterGeoTag }}-glue.example.com:5353 {\n    errors\n  }\n"
		err := os.WriteFile(valuesPath, []byte(valuesContent), 0600)
		require.NoError(t, err)

		options := &helm.Options{
			ValuesFiles: []string{valuesPath},
		}

		output := helm.RenderTemplate(t, options, helmChartPath, "k8gb-test", []string{"templates/coredns/cm.yaml"})

		assert.Contains(t, output, "eu-glue.example.com:5353 {")
	})

	t.Run("omits extraServerBlocks by default", func(t *testing.T) {
		options := &helm.Options{}

		output := helm.RenderTemplate(t, options, helmChartPath, "k8gb-test", []string{"templates/coredns/cm.yaml"})

		assert.NotContains(t, output, "example.com:5353")
		assert.Contains(t, output, ".:5353 {")
		assert.Contains(t, output, "(k8gbplugins) {")
		assert.Contains(t, output, "import ../dynamic/*.conf")
	})
}
