type withdrawnDelegationCleaner struct {
	dns.Provider
	pending bool
	err     error
	name    string
}

func (c *withdrawnDelegationCleaner) CleanupWithdrawnDelegation(name string) (bool, error) {
	c.name = name
	return c.pending, c.err
}

func TestDeletedZoneDelegationContinuesEndpointCleanup(t *testing.T) {
	for _, scenario := range []string{"peer remains", "event-only config", "done", "DNS failure"} {
		t.Run(scenario, func(t *testing.T) {
			ctx := context.Background()
			key := types.NamespacedName{Name: "project.edge"}
			svc := zones.NewMockZoneDelegation(gomock.NewController(t))
			svc.EXPECT().HasAvailableIPs(ctx).Return(true)
			svc.EXPECT().Get(ctx, key).Return(nil, apierrors.NewNotFound(schema.GroupResource{Group: "k8gb.io", Resource: "zonedelegations"}, key.Name))
			cleaner := &withdrawnDelegationCleaner{pending: scenario == "peer remains" || scenario == "event-only config"}
			if scenario == "DNS failure" {
				cleaner.err = errors.New("DNS unavailable")
			}
			r := &ZoneDelegationReconciler{
				Config:      &resolver.Config{ZoneDelegationReconcileRequeueSeconds: 10, ZoneDelegationRecoverySeconds: 5},
				ZoneService: svc, DNSProvider: cleaner, Logger: logging.Logger(),
			}
			if scenario == "event-only config" {
				r.Config.ZoneDelegationReconcileRequeueSeconds = 0
			}
			result, err := r.Reconcile(ctx, ctrl.Request{NamespacedName: key})
			require.Equal(t, key.Name, cleaner.name)
			if scenario == "DNS failure" {
				require.ErrorContains(t, err, "DNS unavailable")
			} else {
				require.NoError(t, err)
				if cleaner.pending {
					require.Equal(t, time.Duration(max(1, r.Config.ZoneDelegationReconcileRequeueSeconds))*time.Second, result.RequeueAfter)
				} else {
					require.Zero(t, result.RequeueAfter)
				}
			}
		})
	}
}
