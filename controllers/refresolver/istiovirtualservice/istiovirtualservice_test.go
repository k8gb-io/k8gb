func TestGetGateway(t *testing.T) {
	var tests = []struct {
		name               string
		virtualServiceGws  []string
		gatewayNamespace   string
		expectedGatewayRef string
		expectedError      bool
	}{
		{
			name:               "gateway qualified with its namespace",
			virtualServiceGws:  []string{"istio-ingress/istio"},
			gatewayNamespace:   "istio-ingress",
			expectedGatewayRef: "istio-ingress/istio",
		},
		{
			name:               "gateway without namespace lives in the namespace of the VirtualService",
			virtualServiceGws:  []string{"istio"},
			gatewayNamespace:   "test-gslb",
			expectedGatewayRef: "test-gslb/istio",
		},
		{
			name:               "mesh is ignored next to a gateway without namespace",
			virtualServiceGws:  []string{"mesh", "istio"},
			gatewayNamespace:   "test-gslb",
			expectedGatewayRef: "test-gslb/istio",
		},
		{
			name:              "gateway without namespace is not looked up in other namespaces",
			virtualServiceGws: []string{"istio"},
			gatewayNamespace:  "istio-ingress",
			expectedError:     true,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			// arrange
			vsYaml := "apiVersion: networking.istio.io/v1\nkind: VirtualService\n" +
				"metadata:\n  name: app\n  namespace: test-gslb\nspec:\n  hosts:\n    - app.cloud.example.com\n  gateways:\n" +
				"    - " + strings.Join(test.virtualServiceGws, "\n    - ") + "\n"
			vs, err := utils.YamlToIstioVirtualService([]byte(vsYaml))
			require.NoError(t, err)
			gwYaml := fmt.Sprintf("apiVersion: networking.istio.io/v1\nkind: Gateway\n"+
				"metadata:\n  name: istio\n  namespace: %s\nspec:\n  selector:\n    istio: ingressgateway\n", test.gatewayNamespace)
			gw, err := utils.YamlToIstioGateway([]byte(gwYaml))
			require.NoError(t, err)
			s := runtime.NewScheme()
			require.NoError(t, istio.AddToScheme(s))
			cl := fake.NewClientBuilder().WithScheme(s).WithObjects(gw).Build()

			// act
			var found *istio.Gateway
			require.NotPanics(t, func() { found, err = getGateway(vs, cl) })

			// assert
			if test.expectedError {
				assert.Error(t, err)
				return
			}
			require.NoError(t, err)
			assert.Equal(t, test.expectedGatewayRef, found.Namespace+"/"+found.Name)
		})
	}
}

func TestGetServers(t *testing.T) {
	var tests = []struct {
		name               string
		virtualServiceFile string
		expectedServers    []*k8gbv1beta1io.Server
	}{
		{
			name:               "single host and route",
			virtualServiceFile: "../testdata/istio_virtualservice.yaml",
			expectedServers: []*k8gbv1beta1io.Server{
				{
					Host: "istio.cloud.example.com",
					Services: []*k8gbv1beta1io.NamespacedName{
						{
							Name:      "istio",
							Namespace: "test-gslb",
						},
					},
				},
			},
		},
		{
			name:               "multiple hosts",
			virtualServiceFile: "./testdata/istio_virtualservice_multiple_hosts.yaml",
			expectedServers: []*k8gbv1beta1io.Server{
				{
					Host: "istio1.cloud.example.com",
					Services: []*k8gbv1beta1io.NamespacedName{
						{
							Name:      "istio",
							Namespace: "test-gslb",
						},
					},
				},
				{
					Host: "istio2.cloud.example.com",
					Services: []*k8gbv1beta1io.NamespacedName{
						{
							Name:      "istio",
							Namespace: "test-gslb",
						},
					},
				},
			},
		},
		{
			name:               "multiple routes",
			virtualServiceFile: "./testdata/istio_virtualservice_multiple_routes.yaml",
			expectedServers: []*k8gbv1beta1io.Server{
				{
					Host: "istio.cloud.example.com",
					Services: []*k8gbv1beta1io.NamespacedName{
						{
							Name:      "istio1",
							Namespace: "test-gslb",
						},
						{
							Name:      "istio2",
							Namespace: "test-gslb",
						},
					},
				},
			},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			// arrange
			vs := utils.FileToIstioVirtualService(test.virtualServiceFile)
			resolver := ReferenceResolver{
				virtualService: vs,
			}

			// act
			servers, err := resolver.GetServers()
			assert.NoError(t, err)

			// assert
			assert.Equal(t, test.expectedServers, servers)
		})
	}
}

func TestGetGslbExposedIPs(t *testing.T) {
	var tests = []struct {
		name          string
		annotations   map[string]string
		serviceYaml   string
		expectedIPs   []string
		expectedError bool
	}{
		{
			name:          "no exposed IPs",
			serviceYaml:   "./testdata/istio_service_no_ips.yaml",
			annotations:   map[string]string{},
			expectedIPs:   []string{},
			expectedError: false,
		},
		{
			name:          "single exposed IP",
			annotations:   map[string]string{},
			serviceYaml:   "../testdata/istio_service.yaml",
			expectedIPs:   []string{"10.0.0.1"},
			expectedError: false,
		},
		{
			name:          "multiple exposed IPs",
			annotations:   map[string]string{},
			serviceYaml:   "./testdata/istio_service_multiple_ips.yaml",
			expectedIPs:   []string{"10.0.0.1", "10.0.0.2"},
			expectedError: false,
		},
		{
			name:          "annotation with no exposed IPs",
			annotations:   map[string]string{"k8gb.io/exposed-ip-addresses": ""},
			serviceYaml:   "./testdata/istio_service_multiple_ips.yaml",
			expectedIPs:   []string{},
			expectedError: true,
		},
		{
			name:          "annotation with single exposed IP",
			annotations:   map[string]string{"k8gb.io/exposed-ip-addresses": "185.199.110.153"},
			serviceYaml:   "./testdata/istio_service_multiple_ips.yaml",
			expectedIPs:   []string{"185.199.110.153"},
			expectedError: false,
		},
		{
			name:          "annotation with invalid IP",
			annotations:   map[string]string{"k8gb.io/exposed-ip-addresses": "192.169.0.test"},
			serviceYaml:   "./testdata/istio_service_multiple_ips.yaml",
			expectedIPs:   []string{},
			expectedError: true,
		},
		{
			name:          "hostname annotation triggers resolution (fails with empty DNS servers)",
			annotations:   map[string]string{"k8gb.io/exposed-hostnames": "myhost.example.com"},
			serviceYaml:   "./testdata/istio_service_multiple_ips.yaml",
			expectedIPs:   nil,
			expectedError: true,
		},
		{
			name:          "hostname annotation takes priority over IP annotation",
			annotations:   map[string]string{"k8gb.io/exposed-hostnames": "myhost.example.com", "k8gb.io/exposed-ip-addresses": "1.2.3.4"},
			serviceYaml:   "./testdata/istio_service_multiple_ips.yaml",
			expectedIPs:   nil,
			expectedError: true,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// arrange
			svc := utils.FileToService(tt.serviceYaml)
			resolver := ReferenceResolver{
				lbService: svc,
			}

			// act
			IPs, err := resolver.GetGslbExposedIPs(tt.annotations, []utils.DNSServer{})
			if tt.expectedError {
				assert.Error(t, err)
			} else {
				assert.NoError(t, err)
			}

			// assert
			assert.Equal(t, tt.expectedIPs, IPs)
		})
	}
}
