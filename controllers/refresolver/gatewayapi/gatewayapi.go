var log = logging.Logger()

// kinds of parent references k8gb follows
const (
	gatewayKind     = "Gateway"
	listenerSetKind = "ListenerSet"
)

// parentRef is a parent reference with the Gateway API defaults applied to its optional fields
type parentRef struct {
	Group     string
	Kind      string
	Namespace string
	Name      string
}

// normalizeParentRef applies the Gateway API defaults to the optional fields of a parent reference:
// group gateway.networking.k8s.io, kind Gateway and the namespace of the referring object
func normalizeParentRef(group *gatewayapiv1.Group, kind *gatewayapiv1.Kind, namespace *gatewayapiv1.Namespace,
	name gatewayapiv1.ObjectName, defaultNamespace string) parentRef {
	ref := parentRef{
		Group:     gatewayapiv1.GroupName,
		Kind:      gatewayKind,
		Namespace: defaultNamespace,
		Name:      string(name),
	}
	if group != nil {
		ref.Group = string(*group)
	}
	if kind != nil {
		ref.Kind = string(*kind)
	}
	if namespace != nil {
		ref.Namespace = string(*namespace)
	}
	return ref
}

func (r parentRef) namespacedName() types.NamespacedName {
	return types.NamespacedName{Namespace: r.Namespace, Name: r.Name}
}

// GetGateway retrieves the gateway referenced by a route resource.
// Parent references to a ListenerSet are followed to the Gateway the ListenerSet is attached to.
func GetGateway(route RouteAdapter, k8sClient client.Client) (*gatewayapiv1.Gateway, error) {
	var gateways []types.NamespacedName
	for _, p := range route.GetParentRefs() {
		ref := normalizeParentRef(p.Group, p.Kind, p.Namespace, p.Name, route.GetNamespace())

		var gatewayRef types.NamespacedName
		switch {
		case ref.Group == gatewayapiv1.GroupName && ref.Kind == gatewayKind:
			gatewayRef = ref.namespacedName()
		case ref.Group == gatewayapiv1.GroupName && ref.Kind == listenerSetKind:
			listenerSetGateway, found, err := getListenerSetGateway(ref.namespacedName(), k8sClient)
			if err != nil {
				return nil, err
			}
			if !found {
				continue
			}
			gatewayRef = listenerSetGateway
		default:
			log.Warn().
				Str("route", route.GetName()).
				Str("namespace", route.GetNamespace()).
				Str("parentRef", ref.Name).
				Msgf("Only Gateway and ListenerSet parent references are supported, got %s in group %q", ref.Kind, ref.Group)
			continue
		}

		// several parentRefs (e.g. ListenerSets) may lead to the same Gateway
		if !slices.Contains(gateways, gatewayRef) {
			gateways = append(gateways, gatewayRef)
		}
	}

	if len(gateways) != 1 {
		return nil, fmt.Errorf("expected exactly 1 Gateway to be referenced by the route but %d were found", len(gateways))
	}

	gateway := &gatewayapiv1.Gateway{}
	err := k8sClient.Get(context.TODO(), gateways[0], gateway)
	if err != nil {
		if errors.IsNotFound(err) {
			log.Info().
				Str("gateway", gateways[0].Name).
				Str("namespace", gateways[0].Namespace).
				Msg("Can't find Gateway resource referenced by route")
		}
		return nil, err
	}
	return gateway, nil
}

// getListenerSetGateway returns the Gateway a ListenerSet is attached to.
// found is false when the ListenerSet does not exist or its parent is not a Gateway; the reason is logged.
func getListenerSetGateway(listenerSetRef types.NamespacedName, k8sClient client.Client) (gatewayRef types.NamespacedName, found bool, err error) {
	listenerSet := &gatewayapiv1.ListenerSet{}
	err = k8sClient.Get(context.TODO(), listenerSetRef, listenerSet)
	if err != nil {
		if errors.IsNotFound(err) {
			log.Info().
				Str("listenerSet", listenerSetRef.Name).
				Str("namespace", listenerSetRef.Namespace).
				Msg("Can't find ListenerSet resource referenced by route")
			return types.NamespacedName{}, false, nil
		}
		return types.NamespacedName{}, false, err
	}

	p := listenerSet.Spec.ParentRef
	parent := normalizeParentRef(p.Group, p.Kind, p.Namespace, p.Name, listenerSet.Namespace)
	if parent.Group != gatewayapiv1.GroupName || parent.Kind != gatewayKind {
		log.Warn().
			Str("listenerSet", listenerSet.Name).
			Str("namespace", listenerSet.Namespace).
			Str("parentRef", parent.Name).
			Msgf("Only Gateway parent references are supported on a ListenerSet, got %s in group %q", parent.Kind, parent.Group)
		return types.NamespacedName{}, false, nil
	}
	return parent.namespacedName(), true, nil
}

// GetServersFromRoute retrieves the GSLB server configuration from a route resource
func GetServersFromRoute(route RouteAdapter) ([]*k8gbv1beta1io.Server, error) {
	hostnames, err := route.GetHostnames()
	if err != nil {
		return nil, err
	}
	if len(hostnames) < 1 {
		return nil, fmt.Errorf("can't find hosts in route %s", route.GetName())
	}

	servers := []*k8gbv1beta1io.Server{}
	for _, hostname := range hostnames {
		server := &k8gbv1beta1io.Server{
			Host:     string(hostname),
			Services: []*k8gbv1beta1io.NamespacedName{},
		}
		for _, rule := range route.GetRules() {
			for _, backendRef := range rule.GetBackendRefs() {
				namespace := route.GetNamespace()
				if backendRef.Namespace != nil {
					namespace = string(*backendRef.Namespace)
				}
				server.Services = append(server.Services, &k8gbv1beta1io.NamespacedName{
					Name:      string(backendRef.Name),
					Namespace: namespace,
				})
			}
		}
		servers = append(servers, server)
	}
	return servers, nil
}

// GetGslbExposedIPs retrieves the load balancer IP address of the GSLB
func GetGslbExposedIPs(gateway *gatewayapiv1.Gateway, gslbAnnotations map[string]string, parentZoneDNSServers utils.DNSList) ([]string, error) {
	// fetch the IP addresses by resolving hostnames from an annotation if it exists
	if hostnames, ok := gslbAnnotations[utils.ExposedHostnamesAnnotation]; ok {
		return utils.ResolveHostnames(hostnames, parentZoneDNSServers...)
	}

	// fetch the IP addresses of the reverse proxy from an annotation if it exists
	if ingressIPsFromAnnotation, ok := gslbAnnotations[utils.ExternalIPsAnnotation]; ok {
		return utils.ParseIPAddresses(ingressIPsFromAnnotation)
	}

	// if there is no annotation -> fetch the IP addresses from the Status of the Gateway resource
	gslbIngressIPs := []string{}
	for _, address := range gateway.Status.Addresses {
		switch {
		case address.Type == nil, *address.Type == gatewayapiv1.AddressType("IPAddress"):
			gslbIngressIPs = append(gslbIngressIPs, address.Value)
		case *address.Type == gatewayapiv1.AddressType("Hostname"):
			IPs, err := utils.Dig(address.Value, 8, parentZoneDNSServers...)
			if err != nil {
				log.Warn().Err(err).Msg("Dig error resolving Gateway API Gateways's hostname")
				return nil, err
			}
			gslbIngressIPs = append(gslbIngressIPs, IPs...)
		default:
			log.Warn().
				Str("gateway", gateway.Name).
				Str("namespace", gateway.Namespace).
				Str("address", address.Value).
				Msg("Unsupported address type")
			return nil, fmt.Errorf("unsupported address type %s", *address.Type)
		}
	}

	return gslbIngressIPs, nil
}
