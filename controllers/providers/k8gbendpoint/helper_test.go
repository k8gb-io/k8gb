func TestGetNSCombinations(t *testing.T) {
	const host = "10.0.0.1"
	tests := []struct {
		name     string
		original []utils.DNSServer
		expected utils.DNSList
	}{
		{
			name:     "single server on default port 53",
			original: []utils.DNSServer{{Host: "edge.example.com", Port: 53}},
			expected: utils.DNSList{{Host: host, Port: 53}},
		},
		{
			name:     "single server on custom port keeps a single probe and adds default 53",
			original: []utils.DNSServer{{Host: "edge.example.com", Port: 5353}},
			expected: utils.DNSList{{Host: host, Port: 5353}, {Host: host, Port: 53}},
		},
		{
			name:     "custom port first, then default port",
			original: []utils.DNSServer{{Host: "edge.example.com", Port: 5353}, {Host: "edge2.example.com", Port: 53}},
			expected: utils.DNSList{{Host: host, Port: 5353}, {Host: host, Port: 53}},
		},
		{
			name:     "default port first, then custom port",
			original: []utils.DNSServer{{Host: "edge.example.com", Port: 53}, {Host: "edge2.example.com", Port: 5353}},
			expected: utils.DNSList{{Host: host, Port: 5353}, {Host: host, Port: 53}},
		},
		{
			name:     "two servers sharing the same custom port collapse to one probe",
			original: []utils.DNSServer{{Host: "edge.example.com", Port: 5353}, {Host: "edge2.example.com", Port: 5353}},
			expected: utils.DNSList{{Host: host, Port: 5353}, {Host: host, Port: 53}},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := getNSCombinations(tt.original, host)
			assert.ElementsMatch(t, tt.expected, got)
			assertNoDuplicatePorts(t, got)
		})
	}
}

func assertNoDuplicatePorts(t *testing.T, list utils.DNSList) {
	t.Helper()
	seen := map[int]bool{}
	for _, s := range list {
		assert.Falsef(t, seen[s.Port], "duplicate nameserver probe for port %d in %v", s.Port, list)
		seen[s.Port] = true
	}
}
