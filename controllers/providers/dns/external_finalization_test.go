func TestExternalDNSWithdrawalAuthorityAddressAlternatives(t *testing.T) {
	clean := withdrawalParent(t, func(w dns.ResponseWriter, r *dns.Msg) { _ = w.WriteMsg(peerOnlyReply(r)) })
	stale := withdrawalParent(t, func(w dns.ResponseWriter, r *dns.Msg) {
		response := peerOnlyReply(r)
		response.Ns = append(response.Ns, &dns.NS{Hdr: dns.RR_Header{Name: dns.Fqdn(withdrawalZone), Rrtype: dns.TypeNS, Class: dns.ClassINET}, Ns: dns.Fqdn(withdrawalLocalNS)})
		_ = w.WriteMsg(response)
	})
	// A closed local UDP/TCP port gives an immediate transport failure.
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	unreachable := listener.Addr().String()
	require.NoError(t, listener.Close())
	provider, zone, _ := withdrawalFixture(t, clean)
	for _, addresses := range [][]string{{unreachable, clean.String()}, {clean.String(), unreachable}} {
		removed, err := provider.localDelegationRemovedAt(zone, [][]string{addresses})
		require.NoError(t, err)
		require.True(t, removed, "one reachable address confirms an authority")
	}
	removed, err := provider.localDelegationRemovedAt(zone, [][]string{{clean.String()}, {unreachable}})
	require.Error(t, err)
	require.False(t, removed, "each authority needs a reachable address")
	removed, err = provider.localDelegationRemovedAt(zone, [][]string{{clean.String(), stale.String()}})
	require.NoError(t, err)
	require.False(t, removed, "a reachable address still publishing us must postpone finalization")
}

func TestExternalDNSDeferredCleanupRequiresAuthoritativePeerAbsence(t *testing.T) {
	for _, scenario := range []string{"empty NOERROR", "stale recursive NXDOMAIN", "nonauthoritative NXDOMAIN", "SOA without AA", "child SOA", "referral", "glue in additional", "CNAME", "authoritative NODATA", "authoritative NXDOMAIN", "missing parent"} {
		t.Run(scenario, func(t *testing.T) {
			var nonrecursiveQueries atomic.Int32
			server := withdrawalParent(t, func(w dns.ResponseWriter, r *dns.Msg) {
				response := peerOnlyReply(r)
				if r.Question[0].Name == dns.Fqdn(withdrawalPeerNS) {
					response = parentNegativeReply(r)
					if !r.RecursionDesired {
						nonrecursiveQueries.Add(1)
					}
					switch scenario {
					case "empty NOERROR":
						response.Authoritative, response.Ns = false, nil
					case "stale recursive NXDOMAIN":
						if r.RecursionDesired {
							response.Authoritative, response.Ns = false, nil
							response.Rcode = dns.RcodeNameError
						} else {
							response.Answer = []dns.RR{&dns.A{Hdr: dns.RR_Header{Name: dns.Fqdn(withdrawalPeerNS), Rrtype: dns.TypeA, Class: dns.ClassINET}, A: net.ParseIP("10.0.0.2")}}
						}
					case "nonauthoritative NXDOMAIN":
						response.Authoritative, response.Ns = false, nil
						response.Rcode = dns.RcodeNameError
					case "SOA without AA":
						response.Authoritative = false
					case "child SOA":
						response.Ns[0].Header().Name = dns.Fqdn(withdrawalZone)
					case "referral":
						response = peerOnlyReply(r)
					case "glue in additional":
						response.Extra = []dns.RR{&dns.A{Hdr: dns.RR_Header{Name: dns.Fqdn(withdrawalPeerNS), Rrtype: dns.TypeA, Class: dns.ClassINET}, A: net.ParseIP("10.0.0.2")}}
					case "CNAME":
						response.Answer = []dns.RR{&dns.CNAME{Hdr: dns.RR_Header{Name: dns.Fqdn(withdrawalPeerNS), Rrtype: dns.TypeCNAME, Class: dns.ClassINET}, Target: "peer.example.com."}}
					case "authoritative NXDOMAIN":
						response.Rcode = dns.RcodeNameError
					}
				}
				_ = w.WriteMsg(response)
			})
			provider, zone, key := withdrawalFixture(t, server)
			require.True(t, provider.Finalize(zone, false).DoFinalization())
			endpoint := &externaldnsApi.DNSEndpoint{}
			require.NoError(t, provider.client.Get(context.Background(), key, endpoint))
			require.Equal(t, withdrawalParentZone, endpoint.Annotations[WithdrawnParentZoneAnnotation])
			if scenario == "missing parent" {
				delete(endpoint.Annotations, WithdrawnParentZoneAnnotation)
				require.NoError(t, provider.client.Update(context.Background(), endpoint))
			}
			// The ZoneDelegation is gone and only persisted annotations survive.
			provider = NewExternalDNS(context.Background(), provider.client, provider.config)
			pending, err := provider.CleanupWithdrawnDelegation(zone.Name())
			if scenario == "authoritative NODATA" || scenario == "authoritative NXDOMAIN" {
				require.NoError(t, err)
				require.False(t, pending)
				require.True(t, apierrors.IsNotFound(provider.client.Get(context.Background(), key, endpoint)))
			} else {
				require.True(t, pending)
				require.NoError(t, provider.client.Get(context.Background(), key, endpoint), "unproven absence must preserve peer records")
			}
			if scenario == "stale recursive NXDOMAIN" {
				require.NoError(t, err)
				require.Positive(t, nonrecursiveQueries.Load(), "cleanup must bypass the stale recursive cache")
			}
		})
	}
}
