func TestExternalDNSWithdrawnEndpointCleanup(t *testing.T) {
	for _, scenario := range []string{"peer remains", "last peer leaves", "redeployment", "DNS failure"} {
		t.Run(scenario, func(t *testing.T) {
			var peerGone atomic.Bool
			server := withdrawalParent(t, func(w dns.ResponseWriter, r *dns.Msg) {
				response := peerOnlyReply(r)
				if r.Question[0].Name == dns.Fqdn(withdrawalPeerNS) {
					if scenario == "DNS failure" {
						response.Rcode = dns.RcodeServerFailure
					} else if !peerGone.Load() {
						response.Answer = []dns.RR{&dns.A{Hdr: dns.RR_Header{Name: dns.Fqdn(withdrawalPeerNS), Rrtype: dns.TypeA, Class: dns.ClassINET}, A: net.ParseIP("10.0.0.2")}}
					} else {
						response = parentNegativeReply(r)
					}
				}
				_ = w.WriteMsg(response)
			})
			provider, zone, key := withdrawalFixture(t, server)
			require.True(t, provider.Finalize(zone, false).DoFinalization())
			// Model a restart after ZoneDelegation deletion: only the endpoint marker persists.
			provider = NewExternalDNS(context.Background(), provider.client, provider.config)
			if scenario == "last peer leaves" {
				peerGone.Store(true)
			}
			if scenario == "redeployment" {
				require.NoError(t, provider.SaveZoneDelegation(zone))
				peerGone.Store(true)
			}
			pending, err := provider.CleanupWithdrawnDelegation(zone.Name())
			endpoint := &externaldnsApi.DNSEndpoint{}
			switch scenario {
			case "peer remains":
				require.NoError(t, err)
				require.True(t, pending)
				require.NoError(t, provider.client.Get(context.Background(), key, endpoint))
				require.Equal(t, zone.Name(), endpoint.Annotations[WithdrawnZoneDelegationAnnotation])
				require.Equal(t, withdrawalParentZone, endpoint.Annotations[WithdrawnParentZoneAnnotation])
			case "last peer leaves":
				require.NoError(t, err)
				require.False(t, pending)
				require.True(t, apierrors.IsNotFound(provider.client.Get(context.Background(), key, endpoint)))
			case "redeployment":
				require.NoError(t, err)
				require.False(t, pending)
				require.NoError(t, provider.client.Get(context.Background(), key, endpoint))
				require.Empty(t, endpoint.Annotations[WithdrawnZoneDelegationAnnotation])
				require.Empty(t, endpoint.Annotations[WithdrawnParentZoneAnnotation])
			case "DNS failure":
				require.Error(t, err)
				require.True(t, pending)
				require.NoError(t, provider.client.Get(context.Background(), key, endpoint))
			}
		})
	}
}

// Emulate a redeployment updating the endpoint between cleanup's read and delete.
type withdrawalConcurrentClient struct{ client.Client }

func (c *withdrawalConcurrentClient) Delete(ctx context.Context, obj client.Object, options ...client.DeleteOption) error {
	current := &externaldnsApi.DNSEndpoint{}
	if err := c.Client.Get(ctx, client.ObjectKeyFromObject(obj), current); err != nil {
		return err
	}
	current.Annotations = nil
	current.Spec.Endpoints = append(current.Spec.Endpoints, &externaldns.Endpoint{DNSName: withdrawalLocalNS, RecordType: "A", Targets: []string{"10.0.0.1"}})
	if err := c.Client.Update(ctx, current); err != nil {
		return err
	}
	return c.Client.Delete(ctx, obj, options...)
}

