const externalDNSTypeCommon = "extdns"

// WithdrawnZoneDelegationAnnotation keeps cleanup independent of the deleted
// ZoneDelegation's lifetime. A new deployment clears it when saving its endpoint.
const WithdrawnZoneDelegationAnnotation = "k8gb.io/withdrawn-zone-delegation"

// WithdrawnParentZoneAnnotation preserves authority discovery after the
// ZoneDelegation has been deleted. Saving a new deployment clears both markers.
const WithdrawnParentZoneAnnotation = "k8gb.io/withdrawn-parent-zone"

type ExternalDNSProvider struct {
	config  resolver.Config
	client  client.Client
	context context.Context
}

var log = logging.Logger()

func NewExternalDNS(ctx context.Context, client client.Client, config resolver.Config) *ExternalDNSProvider {
	return &ExternalDNSProvider{
		context: ctx,
		client:  client,
		config:  config,
	}
}

func (p *ExternalDNSProvider) SaveZoneDelegation(zoneInfo *zones.ExtendedZoneDelegation) error {
	log.Info().
		Str("provider", p.String()).
		Msg("Creating/Updating DNSEndpoint CR")
	// design break for testability - should be passed via constructor
	// consider move this into provider
	dze := k8gbendpoint.NewDelegationDNSEndpoint(p.context, p.client, p.config, log, *zoneInfo)
	ep, err := dze.GetDNSEndpoint()
	if err != nil {
		return fmt.Errorf("failed to create delegationDNSEndpoint %v", err)
	}
	err = dze.SaveDNSEndpoint(ep)
	if err != nil {
		return fmt.Errorf("failed to save delegationDNSEndpoint %v", err)
	}
	return nil
}

func (p *ExternalDNSProvider) Finalize(zoneInfo *zones.ExtendedZoneDelegation, finalizeZone bool) *FinalizationResult {
	if finalizeZone {
		// finalize LoadBalancedZone ( + GluA, SOA and NS records)
		log.Info().Msgf("Removing delegated zone %s from edge DNS", zoneInfo.LoadBalancedZone)
		err := p.deleteZoneDelegated(p.context, zoneInfo)
		return NewFinalization(err)
	}

	// finalize GlueA record only
	log.Info().Msgf("Removing Glue A %s records for delegated zone %s", zoneInfo.ClusterNSName, zoneInfo.LoadBalancedZone)
	if err := p.removeGlueAFromDelegatedZone(p.context, zoneInfo); err != nil {
		return NewErrorFinalization(err)
	}
	// ExternalDNS applies DNSEndpoint changes asynchronously. A successful patch
	// alone does not mean the parent has stopped advertising this nameserver.
	removed, err := p.localDelegationRemoved(zoneInfo)
	if err != nil || !removed {
		return NewDelayedFinalization(err)
	}
	return NewFinalization(nil)
}

func (p *ExternalDNSProvider) String() string {
	return strings.ToUpper(externalDNSTypeCommon)
}

func (p *ExternalDNSProvider) deleteZoneDelegated(ctx context.Context, zone *zones.ExtendedZoneDelegation) error {
	delegationDNSEndpoint := &externaldnsApi.DNSEndpoint{}
	selector := types.NamespacedName{Name: zone.GetZoneDelegation().GetExternalDNSEndpointName(), Namespace: p.config.K8gbNamespace}
	if err := p.client.Get(ctx, selector, delegationDNSEndpoint); err != nil {
		return client.IgnoreNotFound(err)
	}
	return client.IgnoreNotFound(p.client.Delete(ctx, delegationDNSEndpoint))
}

func (p *ExternalDNSProvider) removeGlueAFromDelegatedZone(ctx context.Context, zone *zones.ExtendedZoneDelegation) error {

	delegationDNSEndpoint := &externaldnsApi.DNSEndpoint{}
	selector := types.NamespacedName{Name: zone.GetZoneDelegation().GetExternalDNSEndpointName(), Namespace: p.config.K8gbNamespace}
	if err := p.client.Get(ctx, selector, delegationDNSEndpoint); err != nil {
		return client.IgnoreNotFound(err)
	}

	_, err := controllerutil.CreateOrPatch(ctx, p.client, delegationDNSEndpoint, func() error {
		if delegationDNSEndpoint.Annotations == nil {
			delegationDNSEndpoint.Annotations = map[string]string{}
		}
		delegationDNSEndpoint.Annotations[WithdrawnZoneDelegationAnnotation] = zone.Name()
		delegationDNSEndpoint.Annotations[WithdrawnParentZoneAnnotation] = zone.ParentZone
		delegatedZone := zone.LoadBalancedZone
		glueAName := zone.ClusterNSName

		endpoints := make([]*externaldns.Endpoint, 0, len(delegationDNSEndpoint.Spec.Endpoints))

		for _, ep := range delegationDNSEndpoint.Spec.Endpoints {
			if ep == nil {
				continue
			}

			// Remove Glue A record for the deleted cluster.
			if ep.DNSName == glueAName && ep.RecordType == "A" {
				continue
			}

			// Remove matching NS target from delegated zone.
			if ep.DNSName == delegatedZone && ep.RecordType == "NS" {
				var newTargetList []string
				for _, target := range ep.Targets {
					if target == glueAName {
						continue
					}
					newTargetList = append(newTargetList, target)
				}
				ep.Targets = newTargetList

				if len(newTargetList) == 0 {
					continue
				}
			}

			endpoints = append(endpoints, ep)
		}

		delegationDNSEndpoint.Spec.Endpoints = endpoints

		return nil

	})
	return err
}

// localDelegationRemoved checks the parent authorities discovered through every
// configured DNS server. Peers may still serve the zone during local finalization.
func (p *ExternalDNSProvider) localDelegationRemoved(zone *zones.ExtendedZoneDelegation) (bool, error) {
	servers, err := p.withdrawalParentAuthorities(zone.ParentZone)
	if err != nil {
		return false, err
	}
	return p.localDelegationRemovedAt(zone, servers)
}

// Each authority must confirm withdrawal through a reachable address. Its IPv4
// and IPv6 addresses are alternatives, so IPv4-only clusters can still finalize.
func (p *ExternalDNSProvider) localDelegationRemovedAt(zone *zones.ExtendedZoneDelegation, authorities [][]string) (bool, error) {
	return withdrawalConfirmedAt(authorities, func(server string) (bool, error) {
		return p.localDelegationRemovedFrom(zone, server)
	})
}

func withdrawalConfirmedAt(authorities [][]string, check func(string) (bool, error)) (bool, error) {
	for _, addresses := range authorities {
		confirmed := false
		var lastError error
		for _, server := range addresses {
			removed, err := check(server)
			if err != nil {
				lastError = err
				continue
			}
			if !removed {
				return false, nil
			}
			confirmed = true
		}
		if !confirmed {
			return false, fmt.Errorf("cannot confirm withdrawal at parent authority %v: %w", addresses, lastError)
		}
	}
	return true, nil
}

func (p *ExternalDNSProvider) localDelegationRemovedFrom(zone *zones.ExtendedZoneDelegation, server string) (bool, error) {
	for _, question := range []struct {
		name     string
		typeCode uint16
	}{
		{zone.LoadBalancedZone, dns.TypeNS},
		{zone.ClusterNSName, dns.TypeA},
	} {
		response, err := p.queryWithdrawalDNS(question.name, question.typeCode, server, false)
		if err != nil {
			return false, err
		}
		// Parent NS referrals may be in the authority section; glue can also
		// appear in the additional section rather than the answer section.
		for _, section := range [][]dns.RR{response.Answer, response.Ns, response.Extra} {
			for _, rr := range section {
				switch record := rr.(type) {
				case *dns.NS:
					if strings.EqualFold(record.Hdr.Name, dns.Fqdn(zone.LoadBalancedZone)) &&
						strings.EqualFold(record.Ns, dns.Fqdn(zone.ClusterNSName)) {
						return false, nil
					}
				case *dns.A:
					if strings.EqualFold(record.Hdr.Name, dns.Fqdn(zone.ClusterNSName)) {
						return false, nil
					}
				case *dns.CNAME:
					if strings.EqualFold(record.Hdr.Name, dns.Fqdn(zone.ClusterNSName)) {
						return false, nil
					}
				}
			}
		}
		if !withdrawalParentEvidence(response, zone) {
			return false, fmt.Errorf("no parent delegation evidence from %s for %s", server, question.name)
		}
	}
	return true, nil
}

// withdrawalParentAuthorities uses configured resolvers for discovery only.
// An authoritative NS answer for the exact parent also permits using a directly
// configured authority, preserving custom DNS ports used by private servers.
func (p *ExternalDNSProvider) withdrawalParentAuthorities(parent string) ([][]string, error) {
	if len(p.config.ParentZoneDNSServers) == 0 {
		return nil, fmt.Errorf("cannot confirm delegation withdrawal without parent DNS servers")
	}
	authorities := make(map[string]map[string]struct{})
	for _, resolver := range p.config.ParentZoneDNSServers {
		response, err := p.queryWithdrawalDNS(parent, dns.TypeNS, resolver.String(), true)
		if err != nil {
			return nil, err
		}
		var names []string
		for _, rr := range response.Answer {
			if ns, ok := rr.(*dns.NS); ok && strings.EqualFold(ns.Hdr.Name, dns.Fqdn(parent)) {
				names = append(names, ns.Ns)
			}
		}
		if response.Rcode != dns.RcodeSuccess || len(names) == 0 {
			return nil, fmt.Errorf("cannot discover DNS authorities for parent %s through %s", parent, resolver.String())
		}
		if response.Authoritative {
			authorities[resolver.String()] = map[string]struct{}{resolver.String(): {}}
			continue
		}
		for _, name := range names {
			name = strings.ToLower(dns.Fqdn(name))
			if authorities[name] == nil {
				authorities[name] = make(map[string]struct{})
			}
			resolved := false
			for _, recordType := range []uint16{dns.TypeA, dns.TypeAAAA} {
				addresses, err := p.queryWithdrawalDNS(name, recordType, resolver.String(), true)
				if err != nil {
					return nil, err
				}
				for _, rr := range addresses.Answer {
					if !strings.EqualFold(rr.Header().Name, dns.Fqdn(name)) {
						continue
					}
					var ip net.IP
					switch address := rr.(type) {
					case *dns.A:
						ip = address.A
					case *dns.AAAA:
						ip = address.AAAA
					}
					if ip != nil {
						authorities[name][net.JoinHostPort(ip.String(), "53")] = struct{}{}
						resolved = true
					}
				}
			}
			if !resolved {
				return nil, fmt.Errorf("cannot resolve parent DNS authority %s through %s", name, resolver.String())
			}
		}
	}
	names := make([]string, 0, len(authorities))
	for name := range authorities {
		names = append(names, name)
	}
	sort.Strings(names)
	result := make([][]string, 0, len(names))
	for _, name := range names {
		addresses := make([]string, 0, len(authorities[name]))
		for address := range authorities[name] {
			addresses = append(addresses, address)
		}
		sort.Strings(addresses)
		result = append(result, addresses)
	}
	return result, nil
}

// A referral from a parent authority describes the child's delegation even
// without AA. An absent delegation requires an authoritative negative answer
// carrying the parent's SOA; an empty NOERROR or NXDOMAIN alone proves nothing.
func withdrawalParentEvidence(response *dns.Msg, zone *zones.ExtendedZoneDelegation) bool {
	if response.Rcode == dns.RcodeSuccess && !response.Authoritative {
		for _, rr := range response.Ns {
			if ns, ok := rr.(*dns.NS); ok && strings.EqualFold(ns.Hdr.Name, dns.Fqdn(zone.LoadBalancedZone)) {
				return true
			}
		}
	}
	return withdrawalParentNegative(response, zone.ParentZone)
}

func withdrawalParentNegative(response *dns.Msg, parent string) bool {
	if (response.Rcode == dns.RcodeSuccess || response.Rcode == dns.RcodeNameError) &&
		response.Authoritative && len(response.Answer) == 0 {
		for _, rr := range response.Ns {
			if soa, ok := rr.(*dns.SOA); ok && strings.EqualFold(soa.Hdr.Name, dns.Fqdn(parent)) {
				return true
			}
		}
	}
	return false
}

// peerGlueRemoved requires a negative answer from the parent itself. A referral
// alone cannot prove that a peer's glue has disappeared.
func (p *ExternalDNSProvider) peerGlueRemoved(parent, target string, authorities [][]string) (bool, error) {
	return withdrawalConfirmedAt(authorities, func(server string) (bool, error) {
		response, err := p.queryWithdrawalDNS(target, dns.TypeA, server, false)
		if err != nil {
			return false, err
		}
		for _, section := range [][]dns.RR{response.Answer, response.Ns, response.Extra} {
			for _, rr := range section {
				if strings.EqualFold(rr.Header().Name, dns.Fqdn(target)) &&
					(rr.Header().Rrtype == dns.TypeA || rr.Header().Rrtype == dns.TypeCNAME) {
					return false, nil
				}
			}
		}
		if !withdrawalParentNegative(response, parent) {
			return false, fmt.Errorf("no authoritative parent negative from %s for peer %s", server, target)
		}
		return true, nil
	})
}

func (p *ExternalDNSProvider) queryWithdrawalDNS(name string, recordType uint16, server string, recursive bool) (*dns.Msg, error) {
	msg := new(dns.Msg)
	msg.SetQuestion(dns.Fqdn(name), recordType)
	msg.RecursionDesired = recursive
	dnsClient := &dns.Client{Timeout: 5 * time.Second}
	response, _, err := dnsClient.ExchangeContext(p.context, msg, server)
	if err == nil && response.Truncated {
		dnsClient.Net = "tcp"
		response, _, err = dnsClient.ExchangeContext(p.context, msg, server)
	}
	if err != nil {
		return nil, fmt.Errorf("checking delegation withdrawal at %s: %w", server, err)
	}
	if response.Truncated || (response.Rcode != dns.RcodeSuccess && response.Rcode != dns.RcodeNameError) {
		return nil, fmt.Errorf("checking delegation withdrawal at %s: DNS status %s (truncated=%t)",
			server, dns.RcodeToString[response.Rcode], response.Truncated)
	}
	return response, nil
}

// CleanupWithdrawnDelegation retains peer NS records until their glue has gone,
// without keeping the original ZoneDelegation name occupied. The bool indicates
// that cleanup is still pending and must be retried, including after a restart.
func (p *ExternalDNSProvider) CleanupWithdrawnDelegation(name string) (bool, error) {
	endpoints := &externaldnsApi.DNSEndpointList{}
	if err := p.client.List(p.context, endpoints, client.InNamespace(p.config.K8gbNamespace)); err != nil {
		return false, err
	}
	pending := false
	for _, endpoint := range endpoints.Items {
		if endpoint.Annotations[WithdrawnZoneDelegationAnnotation] != name {
			continue
		}
		parent := endpoint.Annotations[WithdrawnParentZoneAnnotation]
		if parent == "" {
			// Older markers did not persist the parent. Do not guess it from
			// record names: a parent can span several labels or a private zone.
			return true, fmt.Errorf("cannot clean up withdrawn endpoint %s without parent-zone annotation", endpoint.Name)
		}
		authorities, err := p.withdrawalParentAuthorities(parent)
		if err != nil {
			return true, err
		}
		active := false
		for _, record := range endpoint.Spec.Endpoints {
			if record == nil || record.RecordType != "NS" {
				continue
			}
			for _, target := range record.Targets {
				removed, err := p.peerGlueRemoved(parent, target, authorities)
				if err != nil {
					return true, err
				}
				if !removed {
					active = true
				}
			}
		}
		if active {
			pending = true
			continue
		}
		// Avoid deleting an endpoint that a concurrent redeployment has updated.
		if err := p.client.Delete(p.context, &endpoint, client.Preconditions{
			UID: &endpoint.UID, ResourceVersion: &endpoint.ResourceVersion,
		}); client.IgnoreNotFound(err) != nil {
			return true, err
		}
	}
	return pending, nil
}
