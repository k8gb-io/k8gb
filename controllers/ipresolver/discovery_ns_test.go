import (
	"testing"

	"github.com/k8gb-io/k8gb/api/v1beta1io"
	"github.com/k8gb-io/k8gb/controllers/resolver"
	"github.com/miekg/dns"
	"github.com/stretchr/testify/assert"
)

func TestCollectNSFromMsg(t *testing.T) {
	zone := &v1beta1io.ZoneDelegation{
		Spec: v1beta1io.ZoneDelegationSpec{
			LoadBalancedZone: "cloud.example.com",
			ParentZone:       "example.com",
		},
	}
	nsRR := func(name, target string) *dns.NS {
		return &dns.NS{
			Hdr: dns.RR_Header{Name: name, Rrtype: dns.TypeNS, Class: dns.ClassINET},
			Ns:  target,
		}
	}

	tests := []struct {
		name   string
		msg    *dns.Msg
		want   resolver.ClusterNSNames
		geoTag string
	}{
		{
			name:   "authority section only (Infoblox / zone-cut referral)",
			geoTag: "us",
			msg: &dns.Msg{
				Ns: []dns.RR{
					nsRR("cloud.example.com.", "gslb-ns-eu-cloud.example.com."),
					nsRR("cloud.example.com.", "gslb-ns-us-cloud.example.com."),
				},
			},
			want: resolver.ClusterNSNames{
				"gslb-ns-eu-cloud.example.com": resolver.NewGeoTag(false, "eu"),
				"gslb-ns-us-cloud.example.com": resolver.NewGeoTag(true, "us"),
			},
		},
		{
			name:   "answer section only (cloud DNS parent hosting NS records)",
			geoTag: "eu",
			msg: &dns.Msg{
				Answer: []dns.RR{
					nsRR("cloud.example.com.", "gslb-ns-eu-cloud.example.com."),
					nsRR("cloud.example.com.", "gslb-ns-us-cloud.example.com."),
				},
			},
			want: resolver.ClusterNSNames{
				"gslb-ns-eu-cloud.example.com": resolver.NewGeoTag(true, "eu"),
				"gslb-ns-us-cloud.example.com": resolver.NewGeoTag(false, "us"),
			},
		},
		{
			name:   "answer and authority are merged without duplicates",
			geoTag: "eu",
			msg: &dns.Msg{
				Answer: []dns.RR{
					nsRR("cloud.example.com.", "gslb-ns-eu-cloud.example.com."),
				},
				Ns: []dns.RR{
					nsRR("cloud.example.com.", "gslb-ns-eu-cloud.example.com."),
					nsRR("cloud.example.com.", "gslb-ns-za-cloud.example.com."),
				},
			},
			want: resolver.ClusterNSNames{
				"gslb-ns-eu-cloud.example.com": resolver.NewGeoTag(true, "eu"),
				"gslb-ns-za-cloud.example.com": resolver.NewGeoTag(false, "za"),
			},
		},
		{
			name:   "non-k8gb NS names are ignored",
			geoTag: "eu",
			msg: &dns.Msg{
				Answer: []dns.RR{
					nsRR("cloud.example.com.", "ns1.example.com."),
					nsRR("cloud.example.com.", "gslb-ns-eu-cloud.example.com."),
				},
			},
			want: resolver.ClusterNSNames{
				"gslb-ns-eu-cloud.example.com": resolver.NewGeoTag(true, "eu"),
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := collectNSFromMsg(tt.msg, zone, tt.geoTag, "gslb-ns-")
			assert.True(t, resolver.EqualClusterNSNames(tt.want, got), "got %#v want %#v", got, tt.want)
		})
	}
}
