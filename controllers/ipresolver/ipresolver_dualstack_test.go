// Issue #2107: the exposed IPs are published as the NS glue "A" record (delegationDNSEndpoint),
// in the Infoblox delegation and in the ZoneDelegation status, so IPv6 addresses must never be returned.
func TestGetExposedIPsIgnoresIPv6(t *testing.T) {
	const (
		v4 = "192.168.1.1"
		v6 = "fc00:6ce6:4410::161"
	)
	coreDNSService := func(svcType corev1.ServiceType, spec corev1.ServiceSpec, ips ...string) *corev1.Service {
		spec.Type = svcType
		var lbIngress []corev1.LoadBalancerIngress
		for _, ip := range ips {
			lbIngress = append(lbIngress, corev1.LoadBalancerIngress{IP: ip})
		}
		return &corev1.Service{
			ObjectMeta: metav1.ObjectMeta{
				Name: "k8gb-coredns", Namespace: "k8gb",
				Labels: map[string]string{assistant.CoreDNSServiceLabelName: assistant.CoreDNSServiceLabelValue},
			},
			Spec:   spec,
			Status: corev1.ServiceStatus{LoadBalancer: corev1.LoadBalancerStatus{Ingress: lbIngress}},
		}
	}
	ipSourceIngress := func(ips ...string) *netv1.Ingress {
		var lbIngress []netv1.IngressLoadBalancerIngress
		for _, ip := range ips {
			lbIngress = append(lbIngress, netv1.IngressLoadBalancerIngress{IP: ip})
		}
		return &netv1.Ingress{
			ObjectMeta: metav1.ObjectMeta{
				Name: "coredns-ingress", Namespace: "k8gb",
				Labels: map[string]string{assistant.IngressLabelName: assistant.IngressLabelValue},
			},
			Status: netv1.IngressStatus{LoadBalancer: netv1.IngressLoadBalancerStatus{Ingress: lbIngress}},
		}
	}

	tests := []struct {
		name        string
		serviceType corev1.ServiceType // resolver.Config.CoreDNSServiceType
		objects     []client.Object
		expectedIPs []string
		expectedErr string
	}{
		{
			name:        "dual-stack LoadBalancer service",
			serviceType: corev1.ServiceTypeLoadBalancer,
			objects:     []client.Object{coreDNSService(corev1.ServiceTypeLoadBalancer, corev1.ServiceSpec{}, v4, v6)},
			expectedIPs: []string{v4},
		},
		{
			name:        "dual-stack LoadBalancer service, IPv6 listed first",
			serviceType: corev1.ServiceTypeLoadBalancer,
			objects:     []client.Object{coreDNSService(corev1.ServiceTypeLoadBalancer, corev1.ServiceSpec{}, v6, v4)},
			expectedIPs: []string{v4},
		},
		{
			// Spec.ClusterIPs is only read when the configured type is LoadBalancer but the service is a ClusterIP one.
			name:        "dual-stack ClusterIP service (Spec.ClusterIPs)",
			serviceType: corev1.ServiceTypeLoadBalancer,
			objects: []client.Object{coreDNSService(corev1.ServiceTypeClusterIP,
				corev1.ServiceSpec{ClusterIP: "fd03::7ac1", ClusterIPs: []string{"fd03::7ac1", "10.43.207.255"}})},
			expectedIPs: []string{"10.43.207.255"},
		},
		{
			name:        "dual-stack ip-source ingress",
			serviceType: corev1.ServiceTypeClusterIP,
			objects:     []client.Object{ipSourceIngress(v4, v6)},
			expectedIPs: []string{v4},
		},
		{
			name:        "IPv6-only LoadBalancer service",
			serviceType: corev1.ServiceTypeLoadBalancer,
			objects:     []client.Object{coreDNSService(corev1.ServiceTypeLoadBalancer, corev1.ServiceSpec{}, v6)},
			expectedErr: "no IP addresses found",
		},
		{
			name:        "IPv6-only ClusterIP service (Spec.ClusterIPs)",
			serviceType: corev1.ServiceTypeLoadBalancer,
			objects: []client.Object{coreDNSService(corev1.ServiceTypeClusterIP,
				corev1.ServiceSpec{ClusterIP: "fd03::7ac1", ClusterIPs: []string{"fd03::7ac1"}})},
			expectedErr: "no IP addresses found",
		},
		{
			name:        "IPv6-only ip-source ingress",
			serviceType: corev1.ServiceTypeClusterIP,
			objects:     []client.Object{ipSourceIngress(v6)},
			expectedErr: "no IP addresses found",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			cl := fake.NewClientBuilder().WithScheme(scheme.Scheme).WithObjects(test.objects...).Build()
			cfg := &resolver.Config{K8gbNamespace: "k8gb", CoreDNSServiceType: test.serviceType}

			resolved, err := NewResolver(cfg, cl, nil).GetExposedIPs(context.TODO())

			if test.expectedErr != "" {
				require.EqualError(t, err, test.expectedErr)
				assert.Nil(t, resolved)
				return
			}
			require.NoError(t, err)
			assert.Equal(t, test.expectedIPs, resolved.IPs)
		})
	}
}
