import (
	"fmt"
	"strings"
)

func ValidateRFC1035(nsName string) error {
	const dnsNameMax = 253
	const dnsLabelMax = 63
	if len(nsName) > dnsNameMax {
		return fmt.Errorf("%s exceeds %v characters limit", nsName, dnsNameMax)
	}
	labels := strings.Split(nsName, ".")
	for _, l := range labels {
		if len(l) > dnsLabelMax {
			return fmt.Errorf("label %s in %s exceeds %v characters limit", l, nsName, dnsLabelMax)
		}
	}
	return nil
}
