func newFakeDNSServer(t *testing.T, configure func(*DNSMock)) DNSServer {
	t.Helper()

	mock := NewFakeDNS(FakeDNSSettings{
		EdgeDNSZoneFQDN: "example.com.",
		DNSZoneFQDN:     "cloud.example.com.",
	})
	configure(mock)

	packetConn, err := (&net.ListenConfig{}).ListenPacket(context.Background(), "udp", "127.0.0.1:0")
	require.NoError(t, err)

	started := make(chan struct{})
	done := make(chan error, 1)
	server := &dns.Server{
		PacketConn: packetConn,
		Handler:    dns.HandlerFunc(mock.handleReflect),
		NotifyStartedFunc: func() {
			close(started)
		},
	}
	go func() {
		done <- server.ActivateAndServe()
	}()

	select {
	case <-started:
	case serveErr := <-done:
		closeErr := closeTestPacketConn(packetConn)
		assert.NoError(t, closeErr)
		assert.NoError(t, serveErr)
		require.FailNow(t, "fake DNS server stopped before startup")
	}

	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), fakeDNSServerCleanupTimeout)
		shutdownErr := server.ShutdownContext(ctx)
		cancel()

		closeErr := closeTestPacketConn(packetConn)
		var serveErr error
		select {
		case serveErr = <-done:
		case <-time.After(fakeDNSServerCleanupTimeout):
			serveErr = errors.New("timed out waiting for fake DNS server to stop")
		}

		assert.NoError(t, shutdownErr)
		assert.NoError(t, closeErr)
		assert.NoError(t, serveErr)
	})

	address, ok := packetConn.LocalAddr().(*net.UDPAddr)
	require.True(t, ok)
	return DNSServer{Host: address.IP.String(), Port: address.Port}
}

func newBlackholeDNSServer(t *testing.T) DNSServer {
	t.Helper()

	packetConn, err := (&net.ListenConfig{}).ListenPacket(context.Background(), "udp", "127.0.0.1:0")
	require.NoError(t, err)
	t.Cleanup(func() {
		require.NoError(t, packetConn.Close())
	})

	address, ok := packetConn.LocalAddr().(*net.UDPAddr)
	require.True(t, ok)
	return DNSServer{Host: address.IP.String(), Port: address.Port}
}

func closeTestPacketConn(packetConn net.PacketConn) error {
	err := packetConn.Close()
	if errors.Is(err, net.ErrClosed) {
		return nil
	}
	return err
}
