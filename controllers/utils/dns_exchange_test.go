const (
	exchangeTestAnswer = -2
	exchangeTestDrop   = -1
	exchangeTestHost   = "fallback.example.test."
	exchangeTestIP     = "192.0.2.42"
)

func TestExchangeSERVFAILFallback(t *testing.T) {
	first, firstQueries := newExchangeTestServer(t, dns.RcodeServerFailure, 0)
	second, secondQueries := newExchangeTestServer(t, exchangeTestAnswer, 1)
	request := new(dns.Msg)
	request.SetQuestion(exchangeTestHost, dns.TypeA)

	response, err := Exchange(request, []DNSServer{first, second})

	require.NoError(t, err)
	require.NotNil(t, response)
	assert.Equal(t, dns.RcodeSuccess, response.Rcode)
	assert.Equal(t, []string{exchangeTestIP}, NewDNSQueryService().ExtractARecords(response))
	assert.EqualValues(t, 1, firstQueries.Load())
	assert.EqualValues(t, 1, secondQueries.Load())
	t.Logf("queries: SERVFAIL=%d valid=%d", firstQueries.Load(), secondQueries.Load())
}

func TestDigSERVFAILFallback(t *testing.T) {
	first, firstQueries := newExchangeTestServer(t, dns.RcodeServerFailure, 0)
	second, secondQueries := newExchangeTestServer(t, exchangeTestAnswer, 1)

	ips, err := Dig(exchangeTestHost, 8, first, second)

	require.NoError(t, err)
	assert.Equal(t, []string{exchangeTestIP}, ips)
	assert.EqualValues(t, 1, firstQueries.Load())
	assert.EqualValues(t, 1, secondQueries.Load())
}

func TestDNSQueryServiceSERVFAILFallback(t *testing.T) {
	tests := []struct {
		name      string
		servers   []int
		queries   []int32
		status    DNSQueryStatus
		responder int
	}{
		{"servfail_then_answer", []int{dns.RcodeServerFailure, exchangeTestAnswer}, []int32{1, 1}, DNSQueryStatusResolved, 1},
		{"answer_first", []int{exchangeTestAnswer, dns.RcodeServerFailure}, []int32{1, 0}, DNSQueryStatusResolved, 0},
		{"multiple_servfail_then_answer", []int{dns.RcodeServerFailure, dns.RcodeServerFailure, exchangeTestAnswer},
			[]int32{1, 1, 1}, DNSQueryStatusResolved, 2},
		{"all_servfail", []int{dns.RcodeServerFailure, dns.RcodeServerFailure}, []int32{1, 1}, DNSQueryStatusServerFailure, 1},
		{"servfail_then_timeout", []int{dns.RcodeServerFailure, exchangeTestDrop}, []int32{1, 1}, DNSQueryStatusServerFailure, 0},
		{"timeout_then_servfail", []int{exchangeTestDrop, dns.RcodeServerFailure}, []int32{1, 1}, DNSQueryStatusServerFailure, 1},
		{"transport_only", []int{exchangeTestDrop, exchangeTestDrop}, []int32{1, 1}, DNSQueryStatusTimeout, -1},
		{"timeout_then_answer", []int{exchangeTestDrop, exchangeTestAnswer}, []int32{1, 1}, DNSQueryStatusResolved, 1},
		{"servfail_then_nxdomain", []int{dns.RcodeServerFailure, dns.RcodeNameError, exchangeTestAnswer},
			[]int32{1, 1, 0}, DNSQueryStatusNXDOMAIN, 1},
		{"servfail_then_nodata", []int{dns.RcodeServerFailure, dns.RcodeSuccess, exchangeTestAnswer},
			[]int32{1, 1, 0}, DNSQueryStatusNoAnswer, 1},
		{"servfail_then_refused", []int{dns.RcodeServerFailure, dns.RcodeRefused, exchangeTestAnswer},
			[]int32{1, 1, 0}, DNSQueryStatusRefused, 1},
		{"servfail_then_formerr", []int{dns.RcodeServerFailure, dns.RcodeFormatError, exchangeTestAnswer},
			[]int32{1, 1, 0}, DNSQueryStatusError, 1},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			servers := make(DNSList, len(tt.servers))
			counts := make([]*atomic.Int32, len(tt.servers))
			for i, code := range tt.servers {
				servers[i], counts[i] = newExchangeTestServer(t, code, i)
			}

			query := NewDNSQueryService()
			result := query.Query(exchangeTestHost, servers)

			assert.Equal(t, tt.status, result.Status)
			if tt.status == DNSQueryStatusTimeout {
				require.Error(t, result.Err)
				var netErr net.Error
				require.ErrorAs(t, result.Err, &netErr)
				assert.True(t, netErr.Timeout())
				assert.Nil(t, result.Msg)
			} else {
				require.NoError(t, result.Err)
				require.NotNil(t, result.Msg)
				code := tt.servers[tt.responder]
				if code == exchangeTestAnswer {
					code = dns.RcodeSuccess
				}
				assert.Equal(t, code, result.Msg.Rcode)
				// Identify the actual returned response, including the last SERVFAIL on exhaustion.
				require.Len(t, result.Msg.Extra, 1)
				require.IsType(t, &dns.TXT{}, result.Msg.Extra[0])
				assert.Equal(t, []string{strconv.Itoa(tt.responder)}, result.Msg.Extra[0].(*dns.TXT).Txt)
			}
			if tt.status == DNSQueryStatusResolved {
				assert.Equal(t, []string{exchangeTestIP}, query.ExtractARecords(result.Msg))
			} else {
				assert.Empty(t, query.ExtractARecords(result.Msg))
			}
			for i, count := range counts {
				assert.Equal(t, tt.queries[i], count.Load(), "server %d query count", i)
				t.Logf("server %d: queries=%d", i, count.Load())
			}
		})
	}
}

func exchangeTestMarker(id int) *dns.TXT {
	return &dns.TXT{
		Hdr: dns.RR_Header{Name: "responder.example.test.", Rrtype: dns.TypeTXT, Class: dns.ClassINET},
		Txt: []string{strconv.Itoa(id)},
	}
}

func newExchangeTestServer(t *testing.T, code, id int) (DNSServer, *atomic.Int32) {
	t.Helper()
	conn, err := net.ListenUDP("udp4", &net.UDPAddr{IP: net.IPv4(127, 0, 0, 1)})
	require.NoError(t, err)
	count := new(atomic.Int32)
	done := make(chan error, 1)
	t.Cleanup(func() {
		closeErr := conn.Close()
		select {
		case serveErr := <-done:
			assert.NoError(t, serveErr)
		case <-time.After(time.Second):
			t.Error("DNS responder did not stop after its socket was closed")
		}
		assert.NoError(t, closeErr)
	})
	go func() { done <- serveExchangeTestDNS(conn, code, id, count) }()
	addr := conn.LocalAddr().(*net.UDPAddr)
	return DNSServer{Host: addr.IP.String(), Port: addr.Port}, count
}

func serveExchangeTestDNS(conn *net.UDPConn, code, id int, count *atomic.Int32) error {
	buffer := make([]byte, 4096)
	for {
		n, peer, err := conn.ReadFromUDP(buffer)
		if errors.Is(err, net.ErrClosed) {
			return nil
		}
		if err != nil {
			return err
		}
		count.Add(1)
		if code == exchangeTestDrop {
			continue
		}
		request := new(dns.Msg)
		if err := request.Unpack(buffer[:n]); err != nil {
			return err
		}
		if len(request.Question) != 1 {
			return fmt.Errorf("expected one DNS question, got %d", len(request.Question))
		}
		response := new(dns.Msg)
		response.SetReply(request)
		response.Rcode = code
		response.Extra = []dns.RR{exchangeTestMarker(id)}
		if code == exchangeTestAnswer {
			response.Rcode = dns.RcodeSuccess
			response.Answer = []dns.RR{&dns.A{
				Hdr: dns.RR_Header{Name: request.Question[0].Name, Rrtype: dns.TypeA, Class: dns.ClassINET},
				A:   net.ParseIP(exchangeTestIP).To4(),
			}}
		}
		packet, err := response.Pack()
		if err != nil {
			return err
		}
		if _, err := conn.WriteToUDP(packet, peer); err != nil {
			return err
		}
	}
}
