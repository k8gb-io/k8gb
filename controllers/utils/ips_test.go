func TestParseIPAddresses(t *testing.T) {
	tests := []struct {
		name          string
		input         string
		expected      []string
		expectedError bool
	}{
		{
			"single valid IP address",
			"10.0.0.1",
			[]string{"10.0.0.1"},
			false,
		},
		{
			"multiple valid IP addresses",
			"10.0.0.1,10.0.0.2",
			[]string{"10.0.0.1", "10.0.0.2"},
			false,
		},
		{
			"out of 0-255 range",
			"256.256.256.256",
			[]string{},
			true,
		},
		{
			"invalid characters",
			"test.gslb.test.gslb",
			[]string{},
			true,
		},
		{
			"valid and invalid IP addresses",
			"10.0.0.1,test.gslb.test.gslb",
			[]string{},
			true,
		},
		{
			"multiple valid IP addresses with additional comma",
			"10.0.0.1,10.0.0.2,",
			[]string{},
			true,
		},
	}

	// Run each test case
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			ipAddresses, err := ParseIPAddresses(tt.input)
			if tt.expectedError {
				assert.Error(t, err)
			} else {
				assert.NoError(t, err)
			}

			assert.Equal(t, tt.expected, ipAddresses)
		})
	}
}

func TestSplitIPsByVersion(t *testing.T) {
	log := zerolog.Nop()
	tests := []struct {
		name         string
		ips          []string
		expectedIPv4 []string
		expectedIPv6 []string
	}{
		{
			name:         "no addresses",
			ips:          []string{},
			expectedIPv4: []string{},
			expectedIPv6: []string{},
		},
		{
			name:         "invalid address",
			ips:          []string{"invalid"},
			expectedIPv4: []string{},
			expectedIPv6: []string{},
		},
		{
			name:         "single IPv4 address",
			ips:          []string{"192.168.1.1"},
			expectedIPv4: []string{"192.168.1.1"},
			expectedIPv6: []string{},
		},
		{
			name:         "single IPv6 address",
			ips:          []string{"2001:db8::1"},
			expectedIPv4: []string{},
			expectedIPv6: []string{"2001:db8::1"},
		},
		{
			name:         "multiple addresses",
			ips:          []string{"192.168.1.1", "2001:db8::1"},
			expectedIPv4: []string{"192.168.1.1"},
			expectedIPv6: []string{"2001:db8::1"},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			ipv4Addresses, ipv6Addresses := SplitIPsByVersion(&log, test.ips)
			assert.Equal(t, test.expectedIPv4, ipv4Addresses)
			assert.Equal(t, test.expectedIPv6, ipv6Addresses)
		})
	}
}
