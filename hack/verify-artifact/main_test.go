func TestBuildRequirements(t *testing.T) {
	for _, tc := range []struct {
		compiler string
		arch     string
		platform string
		valid    bool
	}{
		{"go1.27.2", "amd64", "linux/amd64", false},
		{"go1.27.3", "amd64", "linux/amd64", true},
		{"go1.27.4", "arm64", "linux/arm64", true},
		{"go1.28.0", "arm64", "linux/arm64", true},
		{"go1.28rc1", "amd64", "linux/amd64", false},
		{"devel go1.28-abcdef", "amd64", "linux/amd64", false},
		{"", "amd64", "linux/amd64", false},
		{"go1.27.3", "amd64", "linux/arm64", false},
		{"go1.27.3", "", "linux/amd64", false},
		{"go1.27.3", "amd64", "darwin/amd64", false},
	} {
		t.Run(tc.compiler+"/"+tc.arch+"/"+tc.platform, func(t *testing.T) {
			info := &debug.BuildInfo{GoVersion: tc.compiler, Settings: []debug.BuildSetting{
				{Key: "GOOS", Value: "linux"}, {Key: "GOARCH", Value: tc.arch},
			}}
			err := checkBuild(info, tc.platform)
			if (err == nil) != tc.valid {
				t.Fatalf("valid=%v, got error %v", tc.valid, err)
			}
		})
	}
}

func TestBundleMatchesKeysNotCertificateNames(t *testing.T) {
	publicKey, privateKey, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	spki, err := x509.MarshalPKIXPublicKey(publicKey)
	if err != nil {
		t.Fatal(err)
	}
	denied := map[string]string{fmt.Sprintf("%x", sha256.Sum256(spki)): "affected key"}
	var bundle []byte
	for i, name := range []string{"Original name", "Different certificate, same key"} {
		template := &x509.Certificate{SerialNumber: big.NewInt(int64(i + 1)), Subject: pkix.Name{CommonName: name}}
		der, err := x509.CreateCertificate(rand.Reader, template, template, publicKey, privateKey)
		if err != nil {
			t.Fatal(err)
		}
		bundle = append(bundle, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})...)
	}
	count, roots, err := checkBundle(bundle, denied)
	if err != nil || count != 2 || len(roots) != 2 {
		t.Fatalf("expected both certificates to match the key, got count=%d roots=%v err=%v", count, roots, err)
	}
	count, roots, err = checkBundle(bundle, affectedRoots)
	if err != nil || count != 2 || len(roots) != 0 {
		t.Fatalf("unrelated certificates rejected: count=%d roots=%v err=%v", count, roots, err)
	}
	for _, malformed := range []string{
		"",
		"not PEM",
		"-----BEGIN CERTIFICATE-----\nnot base64\n-----END CERTIFICATE-----\n",
		"-----BEGIN CERTIFICATE-----\nAA==\n-----END CERTIFICATE-----\n",
		"-----BEGIN CERTIFICATE-----\n",
	} {
		if _, _, err := checkBundle([]byte(malformed), denied); err == nil {
			t.Fatalf("accepted malformed bundle %q", malformed)
		}
		if strings.TrimSpace(malformed) != "" {
			// Valid certificates later in the bundle must not conceal corruption.
			if _, _, err := checkBundle(append([]byte(malformed), bundle...), denied); err == nil {
				t.Fatalf("ignored malformed data preceding a valid certificate: %q", malformed)
			}
		}
	}
	if _, _, err := checkBundle(append(bundle, []byte("trailing garbage")...), denied); err == nil {
		t.Fatal("ignored trailing corruption")
	}
}
