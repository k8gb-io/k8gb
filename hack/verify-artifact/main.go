// Root SPKI hashes, matching the upstream distroless regression check:
// https://github.com/GoogleContainerTools/distroless/blob/29b6e28900d76ffcde3cdc69af252be9c76c8635/common/cacerts_test.go
var affectedRoots = map[string]string{
	"bd153ed7b0434f6886b17bce8bbe84ed340c7132d702a8f4fa318f756ecbd6f3": "AAA Certificate Services",
	"8d417db2dd8bf5e3084d1e3f196d583849d81bdd4c00c70b9d39369e96b8c782": "emSign ECC Root CA - G3",
}

type report struct {
	GoVersion       string   `json:"goVersion"`
	Platform        string   `json:"platform"`
	BinarySHA256    string   `json:"binarySHA256"`
	CABundleSHA256  string   `json:"caBundleSHA256"`
	Certificates    int      `json:"certificates"`
	AffectedRoots   []string `json:"affectedRoots"`
	CleanCARequired bool     `json:"cleanCARequired"`
}

func main() {
	binary := flag.String("binary", "", "path to the extracted Go binary")
	bundle := flag.String("ca-bundle", "", "path to the extracted PEM CA bundle")
	platform := flag.String("platform", "", "expected binary platform (linux/amd64 or linux/arm64)")
	cleanCA := flag.Bool("require-clean-ca", true, "reject affected root keys (false only for ExternalDNS with patched Go)")
	flag.Parse()
	if err := run(*binary, *bundle, *platform, *cleanCA); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(binaryPath, bundlePath, platform string, cleanCA bool) error {
	if binaryPath == "" || bundlePath == "" {
		return fmt.Errorf("both -binary and -ca-bundle are required")
	}
	binary, err := os.ReadFile(binaryPath)
	if err != nil {
		return err
	}
	info, err := buildinfo.Read(bytes.NewReader(binary))
	if err != nil {
		return fmt.Errorf("read binary build metadata: %w", err)
	}
	if err := checkBuild(info, platform); err != nil {
		return err
	}
	bundle, err := os.ReadFile(bundlePath)
	if err != nil {
		return err
	}
	count, roots, err := checkBundle(bundle, affectedRoots)
	if err != nil {
		return err
	}
	result := report{
		GoVersion: info.GoVersion, Platform: platform,
		BinarySHA256:   fmt.Sprintf("%x", sha256.Sum256(binary)),
		CABundleSHA256: fmt.Sprintf("%x", sha256.Sum256(bundle)),
		Certificates:   count, AffectedRoots: roots, CleanCARequired: cleanCA,
	}
	if err := json.NewEncoder(os.Stdout).Encode(result); err != nil {
		return err
	}
	if cleanCA && len(roots) != 0 {
		return fmt.Errorf("CA bundle contains affected root keys: %s", strings.Join(roots, ", "))
	}
	return nil
}

func checkBuild(info *debug.BuildInfo, platform string) error {
	if platform != "linux/amd64" && platform != "linux/arm64" {
		return fmt.Errorf("unsupported platform %q", platform)
	}
	// Require a released compiler on the project's supported Go line or newer.
	// Go 1.26.10 also contains the fix, but k8gb requires Go 1.27.3.
	if !version.IsValid(info.GoVersion) || version.Compare(info.GoVersion, "go1.27.3") < 0 ||
		strings.Contains(info.GoVersion, "rc") || strings.Contains(info.GoVersion, "beta") {
		return fmt.Errorf("binary compiler %q must be a released Go version >= go1.27.3", info.GoVersion)
	}
	settings := make(map[string]string)
	for _, setting := range info.Settings {
		settings[setting.Key] = setting.Value
	}
	actual := settings["GOOS"] + "/" + settings["GOARCH"]
	if actual != platform {
		return fmt.Errorf("binary platform %q does not match %q", actual, platform)
	}
	return nil
}

func checkBundle(bundle []byte, denied map[string]string) (int, []string, error) {
	count := 0
	roots := []string{}
	for len(bytes.TrimSpace(bundle)) != 0 {
		// pem.Decode can skip malformed leading data. Fail instead of reporting
		// success for a bundle that was only partially parsed.
		bundle = bytes.TrimSpace(bundle)
		if !bytes.HasPrefix(bundle, []byte("-----BEGIN CERTIFICATE-----")) {
			return count, roots, fmt.Errorf("unexpected data in CA bundle")
		}
		endMarker := []byte("-----END CERTIFICATE-----")
		end := bytes.Index(bundle, endMarker)
		if end < 0 {
			return count, roots, fmt.Errorf("unterminated certificate in CA bundle")
		}
		end += len(endMarker)
		if bytes.Count(bundle[:end], []byte("-----BEGIN CERTIFICATE-----")) != 1 {
			return count, roots, fmt.Errorf("nested certificate header in CA bundle")
		}
		block, rest := pem.Decode(bundle[:end])
		if block == nil || block.Type != "CERTIFICATE" || len(block.Headers) != 0 || len(rest) != 0 {
			return count, roots, fmt.Errorf("invalid certificate PEM in CA bundle")
		}
		cert, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			return count, roots, fmt.Errorf("invalid certificate in CA bundle: %w", err)
		}
		if name, found := denied[fmt.Sprintf("%x", sha256.Sum256(cert.RawSubjectPublicKeyInfo))]; found {
			roots = append(roots, name)
		}
		count++
		bundle = bundle[end:]
	}
	if count == 0 {
		return 0, roots, fmt.Errorf("CA bundle contains no certificates")
	}
	return count, roots, nil
}
