# Inspect a stopped container; do not execute the image's binary.
set -euo pipefail

if [[ $# -lt 2 || $# -gt 3 ]]; then
  echo "Usage: $0 IMAGE linux/amd64|linux/arm64 [k8gb|external-dns]" >&2
  exit 1
fi

image=$1
platform=$2
case "$platform" in
  linux/amd64|linux/arm64) ;;
  *) echo "Unsupported platform: $platform" >&2; exit 1 ;;
esac
case "${3:-k8gb}" in
  k8gb) binary=/k8gb; require_clean_ca=true ;;
  external-dns) binary=/ko-app/external-dns; require_clean_ca=false ;;
  *) echo "Unknown image profile: $3" >&2; exit 1 ;;
esac

cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
container=
cleanup() {
  if [[ -n "$container" ]]; then docker rm "$container" >/dev/null; fi
  rm -rf "$tmp"
}
trap cleanup EXIT
container=$(docker create --platform "$platform" "$image")
image_id=$(docker inspect --format '{{.Image}}' "$container")
echo "Image: $image ($platform)"
docker image inspect "$image_id" --format 'Image ID: {{.Id}}; repository digests: {{json .RepoDigests}}'
docker cp "$container:$binary" "$tmp/binary"
docker cp "$container:/etc/ssl/certs/ca-certificates.crt" "$tmp/ca-certificates.crt"
go run ./hack/verify-artifact -binary "$tmp/binary" -platform "$platform" \
  -ca-bundle "$tmp/ca-certificates.crt" -require-clean-ca="$require_clean_ca"
